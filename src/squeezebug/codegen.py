"""Turn a minimised failing call into a ready-to-commit pytest file."""

from __future__ import annotations

import ast
import base64
import hashlib
import keyword
import pickle
import pprint
import re
from enum import Enum
from typing import Any

from .runner import CallInput
from .shrink import ShrinkResult


class TestStyle(str, Enum):
    """Shape of the generated test."""

    __test__ = False  # not a pytest test class

    XFAIL = "xfail"
    """``@pytest.mark.xfail(strict=True, raises=...)``: green while the bug exists,
    turns red the moment it is fixed, reminding you to drop the marker and keep a
    real regression test. (default)"""

    RAISES = "raises"
    """``with pytest.raises(...)``: pins the current behaviour exactly."""


def is_literal(value: Any) -> bool:
    """True when ``repr(value)`` round-trips through :func:`ast.literal_eval`."""
    try:
        return ast.literal_eval(repr(value)) == value
    except (ValueError, SyntaxError, TypeError, MemoryError, RecursionError):
        return False


def format_value(value: Any, indent: int = 4) -> str:
    """Pretty-print ``value`` as Python source, indented for a function body."""
    text = pprint.pformat(value, width=88 - indent, sort_dicts=False)
    pad = " " * indent
    return text.replace("\n", "\n" + pad)


def render_call_source(func_name: str, call: CallInput, indent: int = 8) -> tuple[str, list[str]]:
    """Return ``(call_expression, setup_lines)`` reproducing ``call``.

    Literal-safe inputs are inlined; anything else is embedded as a base64
    pickle in the setup lines (with a comment, so reviewers notice).
    """
    tree = call.as_tree()
    if is_literal(tree):
        parts = [format_value(a, indent) for a in call.args]
        for key, val in call.kwargs.items():
            if key.isidentifier() and not keyword.iskeyword(key):
                parts.append(f"{key}={format_value(val, indent)}")
            else:
                return f"{func_name}(*CALL['args'], **CALL['kwargs'])", [
                    f"CALL = {format_value(tree, 4)}"
                ]
        return f"{func_name}({', '.join(parts)})", []
    blob = base64.b64encode(pickle.dumps(tree)).decode("ascii")
    setup = [
        "# Input contains non-literal objects; stored as a pickle generated by squeezebug.",
        f"CALL = pickle.loads(base64.b64decode({blob!r}))",
    ]
    return f"{func_name}(*CALL['args'], **CALL['kwargs'])", setup


def _test_name(qualname: str, result: ShrinkResult) -> str:
    sig = result.signature
    digest = hashlib.sha1(f"{qualname}|{sig.exc_type}|{sig.lineno}".encode()).hexdigest()[:6]
    base = re.sub(r"\W+", "_", qualname).strip("_").lower() or "target"
    return f"test_{base}_squeezebug_{digest}"


def _exception_ref(exc_type: str) -> tuple[str, list[str]]:
    """Return an expression naming the exception class plus imports it needs."""
    if "." not in exc_type:
        return exc_type, []
    module, _, name = exc_type.rpartition(".")
    if "." in name or not module:
        return "Exception", []
    return f"{module}.{name}", [f"import {module}"]


def render_test(
    result: ShrinkResult,
    *,
    module: str,
    qualname: str,
    style: TestStyle = TestStyle.XFAIL,
    explanation: str = "",
) -> str:
    """Render a complete pytest module for ``result``.

    Args:
        result: The shrinking result.
        module: Module to import the target from.
        qualname: Attribute path of the target inside ``module``.
        style: :class:`TestStyle` of the generated test.
        explanation: Optional prose (e.g. from an LLM) added as a comment block.

    Returns:
        Python source code for the test file.
    """
    top, _, rest = qualname.partition(".")
    func_expr = qualname if rest else top
    body_indent = 4 if style is TestStyle.XFAIL else 8
    call_src, setup = render_call_source(func_expr, result.minimized, indent=body_indent)
    exc_expr, exc_imports = _exception_ref(result.signature.exc_type)
    sig = result.signature

    imports = ["import pytest"] + exc_imports
    if any("pickle.loads" in line for line in setup):
        imports = ["import base64", "import pickle"] + imports
    imports.append(f"from {module} import {top}")

    header = [
        f'"""Regression test generated by squeezebug for {module}:{qualname}.',
        "",
        f"Original failure: {sig.short()}",
        f"Input shrunk from size {result.original_size} to {result.minimized_size} "
        f"({result.reduction:.1%} smaller) in {result.calls} calls, match mode '{result.mode.value}'.",
        '"""',
    ]
    lines: list[str] = header + [""] + sorted(set(imports), key=imports.index) + [""]
    if setup:
        lines += setup + [""]
    if explanation.strip():
        lines += ["# Explanation (LLM-generated, verify before trusting):"]
        lines += [f"#   {ln}".rstrip() for ln in explanation.strip().splitlines()]
        lines += [""]
    lines.append("")
    name = _test_name(qualname, result)
    if style is TestStyle.XFAIL:
        lines += [
            f"@pytest.mark.xfail(raises={exc_expr}, strict=True, reason={sig.short()!r})",
            f"def {name}() -> None:",
            "    # Once the bug is fixed this xfail turns into a failure: remove the marker",
            "    # and assert the correct result instead.",
            f"    {call_src}",
        ]
    else:
        lines += [
            f"def {name}() -> None:",
            f"    with pytest.raises({exc_expr}):",
            f"        {call_src}",
        ]
    return "\n".join(lines) + "\n"
